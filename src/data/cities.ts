export function findCity(countrySlug: string, citySlug: string) {
  return cities.find((c) => c.countrySlug === countrySlug && c.slug === citySlug);
}

export function citiesInCountry(countrySlug: string) {
  return cities
    .filter((c) => c.countrySlug === countrySlug)
    .sort((a, b) => b.tourismPriority - a.tourismPriority);
}

export const publishedCities = cities.filter((c) => c.contentStatus === "published");
